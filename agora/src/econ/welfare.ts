// welfare.ts — surplus geometry shared by the equilibrium and intervention models.
// Everything is computed from areas under the linear curves so the accounting is exact
// (consumer + producer surplus + any government revenue + deadweight loss balances).
import type { LinearCurve } from './types';

/**
 * Area under a linear curve from 0 to q: ∫₀^q (intercept + slope·Q) dQ.
 * For demand this is total willingness-to-pay for q units; for supply it's the
 * total cost of producing q units.
 */
export const curveArea = (c: LinearCurve, q: number): number =>
  c.intercept * q + 0.5 * c.slope * q * q;

/** Consumer surplus when q units are bought at price `pBuyer`. */
export const consumerSurplus = (demand: LinearCurve, q: number, pBuyer: number): number =>
  curveArea(demand, q) - pBuyer * q;

/** Producer surplus when q units are sold at price `pSeller`. */
export const producerSurplus = (supply: LinearCurve, q: number, pSeller: number): number =>
  pSeller * q - curveArea(supply, q);

/**
 * Total surplus generated by trading exactly q units, independent of the price it
 * trades at (the price is a pure transfer between the two sides). Maximised at q = Q*.
 */
export const totalSurplusAtQuantity = (
  demand: LinearCurve,
  supply: LinearCurve,
  q: number,
): number => curveArea(demand, q) - curveArea(supply, q);
